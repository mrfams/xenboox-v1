// ─── Bottom Row ────────────────────────────────────────────────────────────

function BottomRow({
  topAccounts,
  recentActivity,
  trendData,
}: {
  topAccounts: Array<{
    name: string;
    debit: number;
    debitFormatted: string;
    credit: number;
    creditFormatted: string;
  }>;
  recentActivity: Array<{
    id: string;
    entryNumber: string;
    action: string;
    timestamp: string;
    user: string;
  }>;
  trendData: Array<{ month: string; count: number }>;
}) {
  const maxTrend = Math.max(...trendData.map((d) => d.count), 1);

  const activityIcons: Record<
    string,
    { icon: typeof CheckCircle2; color: string }
  > = {
    posted: { icon: CheckCircle2, color: "text-emerald-500" },
    "submitted for approval": { icon: Clock, color: "text-amber-500" },
    created: { icon: Plus, color: "text-blue-500" },
    voided: { icon: AlertTriangle, color: "text-red-500" },
  };

  return (
    <div className="grid grid-cols-3 gap-6">
      {/* Journal Entry Trend */}
      <div className="rounded-xl border border-slate-200 bg-white p-5">
        <div className="flex items-center justify-between mb-4">
          <h4 className="text-sm font-medium text-slate-900">
            Journal Entry Trend
          </h4>
          <select className="text-xs text-slate-500 border border-slate-200 rounded px-2 py-1">
            <option>Last 6 months</option>
          </select>
        </div>

        {/* Line Chart */}
        <div className="h-32 flex items-end gap-2">
          {trendData.map((d, _i) => {
            const height = maxTrend > 0 ? (d.count / maxTrend) * 100 : 0;
            return (
              <div
                key={d.month}
                className="flex-1 flex flex-col items-center gap-1"
              >
                <div className="w-full relative" style={{ height: "80px" }}>
                  <div
                    className="absolute bottom-0 w-full bg-gradient-to-t from-indigo-500 to-indigo-400 rounded-t"
                    style={{ height: `${height}%` }}
                  />
                </div>
                <span className="text-[10px] text-slate-500">{d.month}</span>
              </div>
            );
          })}
        </div>
      </div>

      {/* Top Account Impact */}
      <div className="rounded-xl border border-slate-200 bg-white p-5">
        <div className="flex items-center justify-between mb-4">
          <h4 className="text-sm font-medium text-slate-900">
            Top Account Impact (MTD)
          </h4>
          <button className="text-xs font-medium text-indigo-600 hover:text-indigo-700">
            View full report →
          </button>
        </div>
        <div className="space-y-3">
          {topAccounts.map((account) => (
            <div
              key={account.name}
              className="flex items-center justify-between py-2 border-b border-slate-100 last:border-0"
            >
              <span className="text-sm text-slate-700">{account.name}</span>
              <div className="flex items-center gap-4">
                <span className="text-sm font-medium text-slate-900 w-24 text-right">
                  {account.debitFormatted}
                </span>
                <span className="text-sm font-medium text-slate-900 w-24 text-right">
                  {account.creditFormatted}
                </span>
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Recent Activity */}
      <div className="rounded-xl border border-slate-200 bg-white p-5">
        <div className="flex items-center justify-between mb-4">
          <h4 className="text-sm font-medium text-slate-900">
            Recent Activity
          </h4>
          <button className="text-xs font-medium text-indigo-600 hover:text-indigo-700">
            View all activity →
          </button>
        </div>
        <div className="space-y-4">
          {recentActivity.map((activity) => {
            const activityConfig =
              activityIcons[activity.action] ?? activityIcons.created;
            const Icon = activityConfig.icon;
            return (
              <div key={activity.id} className="flex items-start gap-3">
                <Icon className={cn("h-5 w-5 mt-0.5", activityConfig.color)} />
                <div>
                  <p className="text-sm text-slate-900">
                    <span className="font-medium">{activity.entryNumber}</span>{" "}
                    was {activity.action}
                  </p>
                  <p className="text-xs text-slate-500">
                    by {activity.user} •{" "}
                    {new Date(activity.timestamp).toLocaleString("en-US", {
                      hour: "2-digit",
                      minute: "2-digit",
                    })}
                  </p>
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}

