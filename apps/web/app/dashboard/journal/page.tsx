export default function JournalEntriesPage() {
  const [activeTab, setActiveTab] = useState<
    "overview" | "all" | "draft" | "pending" | "approved" | "posted" | "voided"
  >("overview");
  const [searchQuery, setSearchQuery] = useState("");
  const [sourceFilter, setSourceFilter] = useState("");
  const [page, setPage] = useState(1);
  const [pageSize] = useState(10);
  const [showCreate, setShowCreate] = useState(false);
  const [approvingEntry, setApprovingEntry] = useState<{
    id: string;
    entryNumber: string;
    date: string;
    description: string;
    reference: string | null;
    debitFormatted: string;
    creditFormatted: string;
    source: string;
  } | null>(null);

  const utils = trpc.useUtils();
  const postMutation = trpc.journal.post.useMutation({
    onSuccess: () => {
      utils.journal.getOverview.invalidate();
      utils.journal.getTabCounts.invalidate();
      utils.journal.listWithDetails.invalidate();
    },
  });

  // Fetch overview
  const { data: overview } = trpc.journal.getOverview.useQuery({});

  // Fetch tab counts
  const { data: tabCounts } = trpc.journal.getTabCounts.useQuery();

  // Fetch entries
  const { data: entriesData, isLoading: entriesLoading } =
    trpc.journal.listWithDetails.useQuery({
      status: activeTab === "overview" ? "all" : activeTab,
      search: searchQuery || undefined,
      source: sourceFilter || undefined,
      limit: pageSize,
      offset: (page - 1) * pageSize,
    });

  // Fetch top accounts
  const { data: topAccounts } = trpc.journal.getTopAccountImpact.useQuery({
    limit: 5,
  });

  // Fetch sources
  const { data: sources } = trpc.journal.getEntrySources.useQuery({});

  // Fetch recent activity
  const { data: recentActivity } = trpc.journal.getRecentActivity.useQuery();

  // Fetch AI insights + anomaly signals
  const { data: insights } = trpc.journal.getAiInsights.useQuery();
  const { data: outlierSignals } = trpc.journal.getOutlierSignals.useQuery(
    {},
    { enabled: activeTab === "overview" },
  );

  // Fetch monthly trend data for the chart
  const { data: monthlyTrend } = trpc.journal.getMonthlyTrend.useQuery();

  // Fetch pending approval amount
  const { data: pendingAmount } =
    trpc.journal.getPendingApprovalAmount.useQuery();

  const tabs = [
    { key: "overview" as const, label: "Overview" },
    { key: "all" as const, label: "All Entries", count: tabCounts?.all },
    { key: "draft" as const, label: "Draft", count: tabCounts?.draft },
    {
      key: "pending" as const,
      label: "Pending Approval",
      count: tabCounts?.pending,
    },
    { key: "approved" as const, label: "Approved", count: tabCounts?.approved },
    { key: "posted" as const, label: "Posted", count: tabCounts?.posted },
    { key: "voided" as const, label: "Voided", count: tabCounts?.voided },
  ];

  const pagination = (
    <div className="flex items-center justify-between">
      <p className="text-sm text-slate-500">
        Showing {(page - 1) * pageSize + 1} to{" "}
        {Math.min(page * pageSize, entriesData?.totalCount ?? 0)} of{" "}
        {entriesData?.totalCount ?? 0} entries
      </p>
      <div className="flex items-center gap-2">
        <button
          onClick={() => setPage(Math.max(1, page - 1))}
          disabled={page === 1}
          className="px-3 py-1.5 text-sm text-slate-600 hover:bg-slate-50 rounded disabled:opacity-50"
        >
          ←
        </button>
        {Array.from(
          { length: Math.min(5, entriesData?.totalPages ?? 1) },
          (_, i) => i + 1,
        ).map((p) => (
          <button
            key={p}
            onClick={() => setPage(p)}
            className={cn(
              "px-3 py-1.5 text-sm rounded",
              page === p
                ? "bg-indigo-600 text-white"
                : "text-slate-600 hover:bg-slate-50",
            )}
          >
            {p}
          </button>
        ))}
        <button
          onClick={() =>
            setPage(Math.min(entriesData?.totalPages ?? 1, page + 1))
          }
          disabled={page === (entriesData?.totalPages ?? 1)}
          className="px-3 py-1.5 text-sm text-slate-600 hover:bg-slate-50 rounded disabled:opacity-50"
        >
          →
        </button>
        <select
          value={pageSize}
          onChange={() => setPage(1)}
          className="ml-4 rounded-lg border border-slate-200 px-3 py-1.5 text-sm text-slate-700 focus:outline-none focus:ring-2 focus:ring-indigo-500"
        >
          <option value={10}>10 / page</option>
          <option value={25}>25 / page</option>
          <option value={50}>50 / page</option>
        </select>
      </div>
    </div>
  );

  return (
    <ModulePageShell
      title="Journal Entries"
      description="Create, review, and manage journal entries with AI assistance."
      icon={BookOpen}
      actions={
        <>
          <AiSimulationTrigger
            traceId="journal-entry-automation"
            label="AI Draft Entry"
            variant="outline"
          />
          <AiSimulationTrigger
            traceId="journal-review"
            label="AI Review Entries"
            variant="outline"
          />
          <button
            onClick={() => setShowCreate(true)}
            className="inline-flex items-center gap-2 rounded-lg bg-indigo-600 px-3 py-2 text-sm font-medium text-white hover:bg-indigo-700 transition-colors"
          >
            <Plus className="h-4 w-4" />
            New Journal Entry
          </button>
          <button className="inline-flex items-center gap-2 rounded-lg border border-slate-200 bg-white px-3 py-2 text-sm font-medium text-slate-700 hover:bg-slate-50">
            <Upload className="h-4 w-4" />
            Import
          </button>
        </>
      }
      tabs={tabs}
      activeTab={activeTab}
      onTabChange={(key) => {
        setActiveTab(key as (typeof tabs)[number]["key"]);
        setPage(1);
      }}
      summaryCards={
        overview
          ? buildSummaryCards(
              overview,
              pendingAmount ?? { count: 0, totalAmount: 0 },
            )
          : []
      }
      filters={
        <div className="flex items-center gap-3">
          <div className="flex-1 relative">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-slate-400" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Search journal entries..."
              className="w-full rounded-lg border border-slate-200 pl-10 pr-4 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-indigo-500 focus:border-transparent"
            />
          </div>
          <select
            value={sourceFilter}
            onChange={(e) => {
              setSourceFilter(e.target.value);
              setPage(1);
            }}
            className="rounded-lg border border-slate-200 px-3 py-2 text-sm text-slate-700 focus:outline-none focus:ring-2 focus:ring-indigo-500"
          >
            <option value="">All Sources</option>
            {(sources?.sources ?? []).map((s) => (
              <option key={s.name} value={s.name}>
                {s.name}
              </option>
            ))}
          </select>
          {sourceFilter && (
            <button
              onClick={() => {
                setSourceFilter("");
                setPage(1);
              }}
              className="inline-flex items-center gap-1 rounded-lg border border-slate-200 bg-white px-3 py-2 text-xs font-medium text-slate-600 hover:bg-slate-50"
            >
              Clear filter
            </button>
          )}
        </div>
      }
      pagination={activeTab !== "overview" ? pagination : undefined}
    >
      {activeTab === "overview" ? (
        <JournalOverview
          topAccounts={topAccounts}
          recentActivity={recentActivity}
          sources={sources}
          insights={insights}
          outlierSignals={outlierSignals}
        />
      ) : (
        <JournalTable
          entries={entriesData?.entries ?? []}
          isLoading={entriesLoading}
          onApprove={(entry) =>
            setApprovingEntry({
              id: entry.id,
              entryNumber: entry.entryNumber,
              date: entry.date,
              description: entry.description,
              reference: entry.reference,
              debitFormatted: entry.debitFormatted,
              creditFormatted: entry.creditFormatted,
              source: entry.source,
            })
          }
        />
      )}
      <CreateJournalEntryDialog
        open={showCreate}
        onClose={() => setShowCreate(false)}
      />
      <DiffConfirmationDialog
        open={approvingEntry !== null}
        onOpenChange={(open) => {
          if (!open) setApprovingEntry(null);
        }}
        title={`Review & Post ${approvingEntry?.entryNumber ?? ""}`}
        description="Confirm the exact change before posting this entry to the general ledger. This action is audit-logged and irreversible once posted."
        items={
          approvingEntry
            ? [
                {
                  id: approvingEntry.id,
                  title: approvingEntry.description,
                  fields: [
                    {
                      label: "Status",
                      before: "Pending Approval",
                      after: "Posted",
                    },
                    {
                      label: "Date",
                      before: new Date(approvingEntry.date).toLocaleDateString(
                        "en-US",
                        {
                          month: "short",
                          day: "numeric",
                          year: "numeric",
                        },
                      ),
                      after: new Date(approvingEntry.date).toLocaleDateString(
                        "en-US",
                        {
                          month: "short",
                          day: "numeric",
                          year: "numeric",
                        },
                      ),
                    },
                    {
                      label: "Debit",
                      before: approvingEntry.debitFormatted,
                      after: approvingEntry.debitFormatted,
                    },
                    {
                      label: "Credit",
                      before: approvingEntry.creditFormatted,
                      after: approvingEntry.creditFormatted,
                    },
                    {
                      label: "Source",
                      before: approvingEntry.source,
                      after: approvingEntry.source,
                    },
                  ],
                  reason:
                    "This entry is being moved from pending approval to posted. The general ledger will reflect this posting immediately.",
                  confidence: 95,
                },
              ]
            : []
        }
        confirmLabel="Post Entry"
        onConfirm={async () => {
          if (!approvingEntry) return;
          await postMutation.mutateAsync({ id: approvingEntry.id });
          setApprovingEntry(null);
        }}
      />
    </ModulePageShell>
  );
}
